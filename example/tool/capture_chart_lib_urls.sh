#!/usr/bin/env bash
# Regenerates lib/src/config/chart_lib_urls.dart from a real chart load on a connected Android device.
#
# Wipes the app, opens the chart on a fast network, waits until the page has stopped loading files,
# and writes down the full URL of every static file it fetched under /chart/. Run it after a
# TradingView library upgrade or a change to the page's scripts. The device must be on a fast
# network: a throttled link will not finish loading the library inside the harness's budget.
set -uo pipefail

PKG="com.example.ios_webview_plugin_example"
ACT="$PKG/.MainActivity"
DEVICE="${DEVICE:-}"
TIMEOUT="${TIMEOUT:-420}"
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT_DART="$HERE/../lib/src/config/chart_lib_urls.dart"
export LC_ALL=C

adb_() { if [ -n "$DEVICE" ]; then adb -s "$DEVICE" "$@"; else adb "$@"; fi; }
die() { echo "error: $*" >&2; exit 1; }

command -v adb >/dev/null || die "adb not on PATH"
adb_ get-state >/dev/null 2>&1 || die "no device (set DEVICE=<serial> if several are attached)"

echo "· pm clear, then capturing"
adb_ shell pm clear "$PKG" >/dev/null
adb_ logcat -c
adb_ shell am start -n "$ACT" --es scenario WC --ez autorun true >/dev/null

deadline=$(( SECONDS + TIMEOUT ))
while [ $SECONDS -lt $deadline ]; do
  adb_ logcat -d 2>/dev/null | grep -aq "__DONE__" && break
  sleep 3
done
adb_ logcat -d 2>/dev/null | grep -aq "__DONE__" || die "timed out after ${TIMEOUT}s"

lines="$(adb_ logcat -d 2>/dev/null | grep -a HBRESULT | sed -e "s/.*HBRESULT$(printf '\t')//")"
echo "$lines" | grep -aE "^WC$(printf '\t')(PASS|FAIL|ERROR)" | cut -c1-200

tmp="$(mktemp)"
echo "$lines" \
  | awk -F'\t' '$1=="WC" && $2=="EVIDENCE" && $3 ~ /^urls\.[0-9]+$/ {print $3 "\t" $4}' \
  | sort | cut -f2- | tr ' ' '\n' | grep -a '^https\?://' > "$tmp"

count="$(wc -l < "$tmp" | tr -d ' ')"
[ "$count" -gt 20 ] || { rm -f "$tmp"; die "captured only $count urls; is the device on a fast network?"; }

python3 -I - "$tmp" "$OUT_DART" <<'PY'
import sys, re, datetime
urls = [l.strip() for l in open(sys.argv[1]) if l.strip()]
hosts = sorted({re.match(r'https?://[^/]+', u).group(0) for u in urls})
vers = sorted({m.group(0) for u in urls for m in [re.search(r'TT_v[0-9_]+', u)] if m})
body = ",\n".join("  '%s'" % u for u in urls)
open(sys.argv[2], 'w').write(f"""/// Every static file the chart page loads under `/chart/` on a real run, query strings included.
///
/// Fixture for the cache warm-up cases. The warm-up needs the exact URLs because the query string
/// is part of the HTTP cache key (`main.js?v=6` and `main.js` are different entries), and the lazy
/// chunks cannot be found by reading the page's source.
///
/// GENERATED by `tool/capture_chart_lib_urls.sh` on {datetime.date.today().isoformat()}; do not edit.
/// Host: {', '.join(hosts)}. Library: {', '.join(vers) or 'unknown'}. Files: {len(urls)}.
const List<String> kChartLibUrls = <String>[
{body},
];
""")
print(f"wrote {len(urls)} urls -> {sys.argv[2]}")
PY
rm -f "$tmp"
